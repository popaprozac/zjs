  of Eof:               "Eof"
  of Invalid:           "Invalid"
  of Identifier:        "Identifier"
  of NumberLit:         "NumberLit"
  of StringLit:         "StringLit"
  of KwVar:             "KwVar"
  of KwLet:             "KwLet"
  of KwConst:           "KwConst"
  of KwFunction:        "KwFunction"
  of KwReturn:          "KwReturn"
  of KwIf:              "KwIf"
  of KwElse:            "KwElse"
  of KwFor:             "KwFor"
  of KwWhile:           "KwWhile"
  of KwDo:              "KwDo"
  of KwBreak:           "KwBreak"
  of KwContinue:        "KwContinue"
  of KwClass:           "KwClass"
  of KwExtends:         "KwExtends"
  of KwSuper:           "KwSuper"
  of KwNew:             "KwNew"
  of KwThis:            "KwThis"
  of KwTrue:            "KwTrue"
  of KwFalse:           "KwFalse"
  of KwNull:            "KwNull"
  of KwUndefined:       "KwUndefined"
  of KwTypeof:          "KwTypeof"
  of KwDelete:          "KwDelete"
  of KwVoid:            "KwVoid"
  of KwIn:              "KwIn"
  of KwOf:              "KwOf"
  of KwInstanceof:      "KwInstanceof"
  of KwThrow:           "KwThrow"
  of KwTry:             "KwTry"
  of KwCatch:           "KwCatch"
  of KwFinally:         "KwFinally"
  of KwSwitch:          "KwSwitch"
  of KwCase:            "KwCase"
  of KwDefault:         "KwDefault"
  of KwAsync:           "KwAsync"
  of KwAwait:           "KwAwait"
  of KwYield:           "KwYield"
  of KwImport:          "KwImport"
  of KwExport:          "KwExport"
  of KwFrom:            "KwFrom"
  of KwAs:              "KwAs"
  of LParen:            "LParen"
  of RParen:            "RParen"
  of LBracket:          "LBracket"
  of RBracket:          "RBracket"
  of LBrace:            "LBrace"
  of RBrace:            "RBrace"
  of Comma:             "Comma"
  of Semicolon:         "Semicolon"
  of Colon:             "Colon"
  of Dot:               "Dot"
  of Ellipsis:          "Ellipsis"
  of Arrow:             "Arrow"
  of Tilde:             "Tilde"
  of Question:          "Question"
  of QuestionDot:       "QuestionDot"
  of QuestionQuestion:  "QuestionQuestion"
  of QuestionQuestionEq: "QuestionQuestionEq"
  of Bang:              "Bang"
  of BangEq:            "BangEq"
  of BangEqEq:          "BangEqEq"
  of Eq:                "Eq"
  of EqEq:              "EqEq"
  of EqEqEq:            "EqEqEq"
  of Lt:                "Lt"
  of LtEq:              "LtEq"
  of LtLt:              "LtLt"
  of LtLtEq:            "LtLtEq"
