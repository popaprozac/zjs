## nim-lex: dump the token stream in the exact format of `zjs lex`, for
## byte-diffing against the Zen-c reference (the differential oracle).
##
## tkLabel mirrors the Zen-c tools/zjs.zc `tk_label` table exactly:
## kinds absent from that table (BigIntLit, RegexLit, TemplateLit,
## KwWith, KwGet, KwSet, PrivateName) produce "?" just as Zen-c does.
import std/[os, strformat]
import ../src/zjs/lexer
import ../src/zjs/token

